const CW: u32 = 8;
const CH: u32 = 16;

fn pack_rgb(r: u8, g: u8, b: u8, bgr: bool) -> u32 {
    if bgr { ((r as u32) << 16) | ((g as u32) << 8) | (b as u32) }
    else { ((b as u32) << 16) | ((g as u32) << 8) | (r as u32) }
}
/* VGA-ish palette, normal + bright. */
fn palette(idx: u8, bright: bool, bgr: bool) -> u32 {
    let (r, g, b): (u8, u8, u8) = match idx & 7 {
        0 => (0, 0, 0),
        1 => (170, 0, 0),
        2 => (0, 170, 0),
        3 => (170, 85, 0),
        4 => (0, 0, 170),
        5 => (170, 0, 170),
        6 => (0, 170, 170),
        _ => (170, 170, 170),
    };
    if bright && idx != 0 && idx != 7 {
        pack_rgb(r.saturating_add(85), g.saturating_add(85), b.saturating_add(85), bgr)
    } else if idx == 7 && bright {
        pack_rgb(255, 255, 255, bgr)
    } else {
        pack_rgb(r, g, b, bgr)
    }
}

struct Fb {
    base: u64,
    width: u32,
    height: u32,
    stride: u32,
    bgr: bool,
    cols: u32,
    rows: u32,
    cx: u32,
    cy: u32,
    fg: u8,
    bg: u8,
    bright: bool,
    esc: u8, /* 0 normal, 1 got ESC, 2 in CSI */
    csi: [u8; 12],
    csi_len: usize,
}
const NO_FB: Fb = Fb { base: 0, width: 0, height: 0, stride: 0, bgr: false, cols: 0, rows: 0, cx: 0, cy: 0, fg: 7, bg: 0, bright: false, esc: 0, csi: [0; 12], csi_len: 0 };
static FB: IrqSpinLock<Fb> = IrqSpinLock::new(NO_FB);
static ENABLED: AtomicBool = AtomicBool::new(false);

pub fn available() -> bool { ENABLED.load(Ordering::Relaxed) }

/// Map and clear the console. `format`: 0 = RGBR8, 1 = BGRR8.
pub fn init(base_pa: u64, size: u64, width: u32, height: u32, stride: u32, format: u32) -> bool {
    if base_pa == 0 || width == 0 || width > 4096 || height == 0 || height > 4096 {
        return false;
    }
    if stride < width || stride > 16384 || (format != 0 && format != 1) {
        return false;
    }
    let mut need = (stride as u64).saturating_mul(height as u64).saturating_mul(4);
    if size >= need && size <= 64 * 1024 * 1024 {
        need = size;
    }
    if need == 0 || need > 64 * 1024 * 1024 {
        return false;
    }
    let va = crate::driver::pci::ioremap_pa(base_pa, need);
    if va == 0 {
        return false;
    }
    {
        let mut f = FB.lock();
        f.base = va;
        f.width = width;
        f.height = height;
        f.stride = stride;
        f.bgr = format == 1;
        f.cols = width / CW;
        f.rows = height / CH;
        f.cx = 0;
        f.cy = 0;
        f.fg = 7;
        f.bg = 0;
        f.bright = false;
        f.esc = 0;
        f.csi_len = 0;
        if f.cols == 0 || f.rows == 0 {
            f.base = 0;
            return false;
        }
        /* Clear to black. */
        unsafe { core::ptr::write_bytes(va as *mut u8, 0, need as usize) };
    }
    ENABLED.store(true, Ordering::Relaxed);
    true
}

#[inline]
fn px(base: u64, stride: u32, x: u32, y: u32) -> *mut u32 {
    ((base + ((y as u64) * (stride as u64) + (x as u64)) * 4) as *mut u32)
}

fn draw_glyph(f: &Fb, col: u32, row: u32, ch: u8, fg: u32, bg: u32) {
    if col >= f.cols || row >= f.rows {
        return;
    }
    let g = &FONT[(ch as usize).saturating_sub(32).min(94)];
    let x0 = col * CW;
    let y0 = row * CH;
    for r in 0..16u32 {
        let bits = g[(r / 2) as usize];
        for c in 0..8u32 {
            let on = (bits >> (7 - c)) & 1 == 1;
            unsafe { px(f.base, f.stride, x0 + c, y0 + r).write_volatile(if on { fg } else { bg }) };
        }
    }
}

fn draw_cursor(f: &Fb) {
    if f.cx >= f.cols || f.cy >= f.rows {
        return;
    }
    let fg = palette(f.fg, f.bright, f.bgr);
    let x0 = f.cx * CW;
    let y0 = f.cy * CH;
    for r in 0..CH {
        for c in 0..CW {
            unsafe { px(f.base, f.stride, x0 + c, y0 + r).write_volatile(fg) };
        }
    }
}

fn erase_cell(f: &Fb, col: u32, row: u32) {
    if col >= f.cols || row >= f.rows {
        return;
    }
    let bg = palette(f.bg, false, f.bgr);
    let x0 = col * CW;
    let y0 = row * CH;
    for r in 0..CH {
        for c in 0..CW {
            unsafe { px(f.base, f.stride, x0 + c, y0 + r).write_volatile(bg) };
        }
    }
}

fn scroll(fb: &mut Fb) {
    let row_bytes = (fb.stride as u64) * 4 * (CH as u64);
    let total = (fb.stride as u64) * (fb.height as u64) * 4;
    unsafe {
        let base = fb.base as *mut u8;
        core::ptr::copy(base.add(row_bytes as usize), base, (total - row_bytes) as usize);
        let bg32 = palette(fb.bg, false, fb.bgr);
        let mut p = base.add((total - row_bytes) as usize) as *mut u32;
        let n = (row_bytes / 4) as usize;
        for i in 0..n {
            p.add(i).write_volatile(bg32);
        }
    }
    if fb.cy > 0 {
        fb.cy -= 1;
    }
}

fn newline(fb: &mut Fb) {
    fb.cx = 0;
    fb.cy += 1;
    if fb.cy >= fb.rows {
        scroll(fb);
    }
}

fn put_byte(fb: &mut Fb, b: u8) {
    /* Minimal CSI parser: ESC [ params m (SGR only). */
    if fb.esc == 1 {
        if b == b'[' {
            fb.esc = 2;
            fb.csi_len = 0;
        } else {
            fb.esc = 0;
        }
        return;
    }
    if fb.esc == 2 {
        if b.is_ascii_digit() || b == b';' {
            if fb.csi_len < fb.csi.len() {
                fb.csi[fb.csi_len] = b;
                fb.csi_len += 1;
            }
            return;
        }
        if b == b'm' {
            apply_sgr(fb);
        }
        fb.esc = 0;
        return;
    }
    match b {
        b'\n' => newline(fb),
        b'\r' => fb.cx = 0,
        b'\t' => {
            fb.cx = (fb.cx + 8) & !7;
            if fb.cx >= fb.cols {
                newline(fb);
            }
        }
        0x08 => {
            if fb.cx > 0 {
                fb.cx -= 1;
                erase_cell(fb, fb.cx, fb.cy);
            }
        }
        0x1b => fb.esc = 1,
        0x20..=0x7e => {
            if fb.cx >= fb.cols {
                newline(fb);
            }
            let fg = palette(fb.fg, fb.bright, fb.bgr);
            let bg = palette(fb.bg, false, fb.bgr);
            erase_cell(fb, fb.cx, fb.cy);
            draw_glyph(fb, fb.cx, fb.cy, b, fg, bg);
            fb.cx += 1;
        }
        _ => {}
    }
}

fn apply_sgr(fb: &mut Fb) {
    if fb.csi_len == 0 {
        fb.fg = 7;
        fb.bg = 0;
        fb.bright = false;
        return;
    }
    let mut val: u8 = 0;
    let mut any = false;
    let mut i = 0;
    while i <= fb.csi_len {
        let end = i == fb.csi_len || fb.csi[i] == b';';
        if end {
            apply_sgr_param(fb, if any { val } else { 0 });
            val = 0;
            any = false;
        } else if fb.csi[i].is_ascii_digit() {
            val = val.saturating_mul(10).saturating_add(fb.csi[i] - b'0');
            any = true;
        }
        i += 1;
    }
}

fn apply_sgr_param(fb: &mut Fb, p: u8) {
    match p {
        0 => {
            fb.fg = 7;
            fb.bg = 0;
            fb.bright = false;
        }
        1 => fb.bright = true,
        22 => fb.bright = false,
        30..=37 => fb.fg = p - 30,
        39 => fb.fg = 7,
        40..=47 => fb.bg = p - 40,
        49 => fb.bg = 0,
        _ => {}
    }
}

pub fn write_str(s: &str) {
    if !ENABLED.load(Ordering::Relaxed) {
        return;
    }
    let mut fb = FB.lock();
    if fb.base == 0 {
        return;
    }
    erase_cursor(&fb);
    for &b in s.as_bytes() {
        put_byte(&mut fb, b);
    }
    draw_cursor(&fb);
}

fn erase_cursor(fb: &Fb) {
    /* Cursor always sits on unwritten (background) space. */
    erase_cell(fb, fb.cx, fb.cy);
}
