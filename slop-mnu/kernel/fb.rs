//! font8x8_basic by Daniel Hepper, rows doubled). Mirrors the serial
//! console: kernel log (console::print) and TTY output
//! (console::write_bytes) both render here when a framebuffer exists.
//! Falls back to serial-only when the loader reports no framebuffer.
//! SMP-safe via spinlock; no heap, no allocs (panic-safe path).
